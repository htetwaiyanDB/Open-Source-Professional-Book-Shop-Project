-- Canonical private PostgreSQL schema. Apply the CLI-generated migration, not
-- the legacy MySQL dump. PHP alone holds bookshop_app credentials and establishes
-- transaction-local app.user_id from its validated, server-side session.
BEGIN;

DO $roles$
DECLARE membership record; unsafe record;
BEGIN
  IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = 'bookshop_app') THEN
    CREATE ROLE bookshop_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE
      NOINHERIT NOREPLICATION NOBYPASSRLS;
  END IF;
  -- The Supabase `postgres` migration owner has CREATEROLE but is not a
  -- superuser, so it cannot ALTER superuser/replication/BYPASSRLS attributes.
  -- Verify those attributes instead of attempting a superuser-only alteration.
  SELECT rolsuper, rolreplication, rolbypassrls, rolcreatedb, rolcreaterole
    INTO unsafe FROM pg_catalog.pg_roles WHERE rolname = 'bookshop_app';
  IF unsafe.rolsuper OR unsafe.rolreplication OR unsafe.rolbypassrls
    OR unsafe.rolcreatedb OR unsafe.rolcreaterole THEN
    RAISE EXCEPTION 'bookshop_app has unsafe role attributes; have a Supabase administrator correct them before migrating'
      USING ERRCODE = '42501';
  END IF;
  ALTER ROLE bookshop_app LOGIN NOCREATEDB NOCREATEROLE NOINHERIT;
  -- NOINHERIT alone does not prevent SET ROLE; remove inherited memberships.
  FOR membership IN
    SELECT parent.rolname FROM pg_catalog.pg_auth_members m
    JOIN pg_catalog.pg_roles parent ON parent.oid = m.roleid
    JOIN pg_catalog.pg_roles child ON child.oid = m.member
    WHERE child.rolname = 'bookshop_app'
  LOOP
    EXECUTE pg_catalog.format('REVOKE %I FROM bookshop_app', membership.rolname);
  END LOOP;
END
$roles$;

CREATE SCHEMA bookshop AUTHORIZATION postgres;
REVOKE ALL ON SCHEMA bookshop FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA bookshop REVOKE ALL ON TABLES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA bookshop REVOKE ALL ON SEQUENCES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA bookshop REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;

CREATE TABLE bookshop.author (
  authorid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  authorname text NOT NULL CHECK (char_length(btrim(authorname)) BETWEEN 1 AND 200)
);
CREATE TABLE bookshop.categorys (
  catid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  catname text NOT NULL CHECK (char_length(btrim(catname)) BETWEEN 1 AND 200)
);
CREATE TABLE bookshop.products (
  productid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  productname text NOT NULL CHECK (char_length(btrim(productname)) BETWEEN 1 AND 255),
  categoryid bigint NOT NULL REFERENCES bookshop.categorys(catid),
  price numeric(12,2) NOT NULL CHECK (price BETWEEN 0 AND 9999999999.99),
  qty integer NOT NULL DEFAULT 0 CHECK (qty >= 0),
  photo text NOT NULL DEFAULT '' CHECK (char_length(photo) <= 255),
  authorid bigint NOT NULL REFERENCES bookshop.author(authorid),
  description text NOT NULL DEFAULT '' CHECK (char_length(description) <= 1000)
);
CREATE TABLE bookshop.product_details (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id bigint NOT NULL UNIQUE REFERENCES bookshop.products(productid) ON DELETE CASCADE,
  slug text NOT NULL CHECK (char_length(slug) <= 255),
  description text NOT NULL DEFAULT '' CHECK (char_length(description) <= 100000),
  pages integer NOT NULL DEFAULT 0 CHECK (pages >= 0),
  authorid bigint NOT NULL REFERENCES bookshop.author(authorid)
);
CREATE TABLE bookshop.users (
  userid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username text NOT NULL CHECK (username = btrim(username) AND char_length(username) BETWEEN 1 AND 100),
  password text NOT NULL CHECK (password ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$'),
  email text NOT NULL DEFAULT '' CHECK (char_length(email) <= 254),
  phone text NOT NULL DEFAULT '' CHECK (char_length(phone) <= 30),
  address text NOT NULL DEFAULT '' CHECK (char_length(address) <= 1000),
  role text NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin'))
);
CREATE UNIQUE INDEX users_username_ci ON bookshop.users (lower(username));
CREATE UNIQUE INDEX users_email_ci_nonempty ON bookshop.users (lower(email)) WHERE btrim(email) <> '';
CREATE TABLE bookshop.feedback (
  feedbackid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 100),
  email text NOT NULL CHECK (char_length(btrim(email)) BETWEEN 1 AND 254),
  phone text NOT NULL DEFAULT '' CHECK (char_length(phone) <= 30),
  message text NOT NULL CHECK (char_length(btrim(message)) BETWEEN 1 AND 5000)
);
CREATE TABLE bookshop.comments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  productid bigint NOT NULL REFERENCES bookshop.products(productid) ON DELETE CASCADE,
  userid bigint NOT NULL REFERENCES bookshop.users(userid) ON DELETE CASCADE,
  content text NOT NULL CHECK (char_length(btrim(content)) BETWEEN 1 AND 2000)
);
CREATE TABLE bookshop.orders (
  orderid bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customerid bigint NOT NULL REFERENCES bookshop.users(userid),
  deliveryname text NOT NULL CHECK (char_length(btrim(deliveryname)) BETWEEN 1 AND 255),
  deliveryphone text NOT NULL CHECK (char_length(btrim(deliveryphone)) BETWEEN 1 AND 30),
  email text NOT NULL DEFAULT '' CHECK (char_length(email) <= 254),
  orderdate date NOT NULL DEFAULT CURRENT_DATE,
  status integer NOT NULL DEFAULT 0 CHECK (status IN (0,1)),
  senddate date,
  deliveryaddress text NOT NULL CHECK (char_length(btrim(deliveryaddress)) BETWEEN 1 AND 1000)
);
CREATE TABLE bookshop.orderdetails (
  orderid bigint NOT NULL REFERENCES bookshop.orders(orderid) ON DELETE CASCADE,
  productid bigint NOT NULL REFERENCES bookshop.products(productid),
  productqty integer NOT NULL CHECK (productqty BETWEEN 1 AND 999),
  unit_price numeric(12,2) NOT NULL CHECK (unit_price BETWEEN 0 AND 9999999999.99),
  amount numeric(16,2) NOT NULL CHECK (amount = unit_price * productqty),
  PRIMARY KEY (orderid, productid)
);
CREATE INDEX products_categoryid_idx ON bookshop.products(categoryid);
CREATE INDEX products_authorid_idx ON bookshop.products(authorid);
CREATE INDEX product_details_authorid_idx ON bookshop.product_details(authorid);
CREATE INDEX comments_productid_idx ON bookshop.comments(productid);
CREATE INDEX comments_userid_idx ON bookshop.comments(userid);
CREATE INDEX orders_customerid_idx ON bookshop.orders(customerid);
CREATE INDEX orders_status_idx ON bookshop.orders(status);
CREATE INDEX orderdetails_productid_idx ON bookshop.orderdetails(productid);

-- Invalid/missing identity fails closed, including overflow and whitespace.
CREATE FUNCTION bookshop.current_user_id() RETURNS bigint
LANGUAGE plpgsql STABLE SET search_path = '' AS $fn$
DECLARE value text := pg_catalog.current_setting('app.user_id', true);
BEGIN
  IF value IS NULL OR value !~ '^[1-9][0-9]{0,18}$' THEN RETURN NULL; END IF;
  BEGIN RETURN value::bigint;
  EXCEPTION WHEN numeric_value_out_of_range THEN RETURN NULL;
  END;
END
$fn$;

-- Owner bypasses users RLS, preventing recursive policies. No JWT/session role.
CREATE FUNCTION bookshop.is_admin() RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $fn$
  SELECT EXISTS (SELECT 1 FROM bookshop.users u
    WHERE u.userid = bookshop.current_user_id() AND u.role = 'admin')
$fn$;

CREATE FUNCTION bookshop.login_record(p_username text)
RETURNS TABLE(userid bigint, username text, password text, role text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $fn$
  SELECT u.userid, u.username, u.password, u.role FROM bookshop.users u
    WHERE pg_catalog.lower(u.username) = pg_catalog.lower(pg_catalog.btrim(p_username))
       OR (pg_catalog.btrim(u.email) <> '' AND pg_catalog.lower(u.email) = pg_catalog.lower(pg_catalog.btrim(p_username)))
    LIMIT 1
$fn$;

CREATE FUNCTION bookshop.register_user(p_username text, p_hash text, p_email text, p_phone text, p_address text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $fn$
DECLARE new_id bigint;
BEGIN
  INSERT INTO bookshop.users(username,password,email,phone,address,role)
    VALUES (pg_catalog.btrim(p_username),p_hash,p_email,p_phone,p_address,'user')
    RETURNING userid INTO new_id;
  RETURN new_id;
END
$fn$;

CREATE FUNCTION bookshop.admin_create_user(p_username text, p_hash text, p_email text, p_phone text, p_address text, p_role text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $fn$
DECLARE new_id bigint;
BEGIN
  IF NOT bookshop.is_admin() THEN RAISE EXCEPTION 'Administrator required' USING ERRCODE = '42501'; END IF;
  INSERT INTO bookshop.users(username,password,email,phone,address,role)
    VALUES (pg_catalog.btrim(p_username),p_hash,p_email,p_phone,p_address,p_role)
    RETURNING userid INTO new_id;
  RETURN new_id;
END
$fn$;

CREATE FUNCTION bookshop.admin_delete_user(p_userid bigint)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $fn$
BEGIN
  IF NOT bookshop.is_admin() THEN RAISE EXCEPTION 'Administrator required' USING ERRCODE = '42501'; END IF;
  IF p_userid = bookshop.current_user_id() THEN RAISE EXCEPTION 'Cannot delete current administrator' USING ERRCODE = '22023'; END IF;
  DELETE FROM bookshop.users WHERE userid = p_userid;
  -- Orders deliberately retain a restrictive FK: no loss of financial history.
END
$fn$;

CREATE FUNCTION bookshop.checkout(p_cart jsonb, p_deliveryname text, p_email text, p_deliveryphone text, p_address text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $fn$
DECLARE
  customer bigint := bookshop.current_user_id();
  item jsonb;
  requested record;
  stock record;
  new_order bigint;
  n integer := 0;
BEGIN
  IF customer IS NULL OR NOT EXISTS (SELECT FROM bookshop.users WHERE userid = customer) THEN
    RAISE EXCEPTION 'Authenticated customer required' USING ERRCODE = '42501';
  END IF;
  IF p_cart IS NULL OR pg_catalog.jsonb_typeof(p_cart) <> 'array' THEN
    RAISE EXCEPTION 'Cart must be an array' USING ERRCODE = '22023';
  END IF;
  IF pg_catalog.jsonb_array_length(p_cart) NOT BETWEEN 1 AND 100 THEN
    RAISE EXCEPTION 'Cart must contain 1 to 100 lines' USING ERRCODE = '22023';
  END IF;
  FOR item IN SELECT value FROM pg_catalog.jsonb_array_elements(p_cart) LOOP
    IF pg_catalog.jsonb_typeof(item) <> 'object' OR
      NOT (item ? 'productid' AND item ? 'qty') OR
      (SELECT count(*) FROM pg_catalog.jsonb_object_keys(item)) <> 2 OR
      pg_catalog.jsonb_typeof(item->'productid') <> 'number' OR
      pg_catalog.jsonb_typeof(item->'qty') <> 'number' OR
      (item->>'productid') !~ '^[1-9][0-9]{0,17}$' OR
      (item->>'qty') !~ '^[1-9][0-9]{0,2}$' THEN
      RAISE EXCEPTION 'Invalid cart line (numeric productid and qty 1..999 only)' USING ERRCODE = '22023';
    END IF;
  END LOOP;
  IF (SELECT count(DISTINCT value->>'productid') FROM pg_catalog.jsonb_array_elements(p_cart))
      <> pg_catalog.jsonb_array_length(p_cart) THEN
    RAISE EXCEPTION 'Duplicate product in cart' USING ERRCODE = '22023';
  END IF;
  IF p_deliveryname IS NULL OR char_length(pg_catalog.btrim(p_deliveryname)) NOT BETWEEN 1 AND 255
    OR p_deliveryphone IS NULL OR char_length(pg_catalog.btrim(p_deliveryphone)) NOT BETWEEN 1 AND 30
    OR p_address IS NULL OR char_length(pg_catalog.btrim(p_address)) NOT BETWEEN 1 AND 1000
    OR p_email IS NULL OR char_length(p_email) > 254 THEN
    RAISE EXCEPTION 'Invalid customer delivery details' USING ERRCODE = '22023';
  END IF;
  -- Acquire every inventory lock in deterministic ID order before any write.
  FOR stock IN
    SELECT p.productid,p.qty FROM bookshop.products p
      JOIN pg_catalog.jsonb_to_recordset(p_cart) AS c(productid bigint,qty integer)
        ON c.productid = p.productid
      ORDER BY p.productid FOR UPDATE OF p
  LOOP
    n := n + 1;
    SELECT c.qty INTO requested FROM pg_catalog.jsonb_to_recordset(p_cart) AS c(productid bigint,qty integer)
      WHERE c.productid = stock.productid;
    IF requested.qty > stock.qty THEN
      RAISE EXCEPTION 'Insufficient stock for product %', stock.productid USING ERRCODE = '22023';
    END IF;
  END LOOP;
  IF n <> pg_catalog.jsonb_array_length(p_cart) THEN
    RAISE EXCEPTION 'Unknown cart product' USING ERRCODE = '22023';
  END IF;
  INSERT INTO bookshop.orders(customerid,deliveryname,email,deliveryphone,deliveryaddress)
    VALUES(customer,pg_catalog.btrim(p_deliveryname),p_email,pg_catalog.btrim(p_deliveryphone),pg_catalog.btrim(p_address))
    RETURNING orderid INTO new_order;
  INSERT INTO bookshop.orderdetails(orderid,productid,productqty,unit_price,amount)
    SELECT new_order,p.productid,c.qty,p.price,p.price*c.qty
    FROM bookshop.products p
    JOIN pg_catalog.jsonb_to_recordset(p_cart) AS c(productid bigint,qty integer) ON p.productid=c.productid;
  UPDATE bookshop.products p SET qty=p.qty-c.qty
    FROM pg_catalog.jsonb_to_recordset(p_cart) AS c(productid bigint,qty integer)
    WHERE p.productid=c.productid;
  RETURN new_order;
END
$fn$;

-- Every table is postgres-owned and RLS-enabled; NOT FORCE intentionally:
-- the narrowly granted postgres-owned definers must bypass users/inventory RLS.
DO $rls$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['author','categorys','products','product_details','users','feedback','comments','orders','orderdetails'] LOOP
    EXECUTE pg_catalog.format('ALTER TABLE bookshop.%I OWNER TO postgres',t);
    EXECUTE pg_catalog.format('ALTER TABLE bookshop.%I ENABLE ROW LEVEL SECURITY',t);
  END LOOP;
  FOREACH t IN ARRAY ARRAY['author','categorys','products','product_details'] LOOP
    EXECUTE pg_catalog.format('CREATE POLICY catalog_read ON bookshop.%I FOR SELECT TO bookshop_app USING (true)',t);
    EXECUTE pg_catalog.format('CREATE POLICY catalog_admin ON bookshop.%I FOR ALL TO bookshop_app USING ((SELECT bookshop.is_admin())) WITH CHECK ((SELECT bookshop.is_admin()))',t);
  END LOOP;
END
$rls$;
CREATE POLICY users_read ON bookshop.users FOR SELECT TO bookshop_app
  USING (userid=(SELECT bookshop.current_user_id()) OR (SELECT bookshop.is_admin()));
CREATE POLICY users_edit ON bookshop.users FOR UPDATE TO bookshop_app
  USING (userid=(SELECT bookshop.current_user_id()) OR (SELECT bookshop.is_admin()))
  WITH CHECK (userid=(SELECT bookshop.current_user_id()) OR (SELECT bookshop.is_admin()));
CREATE POLICY comments_read ON bookshop.comments FOR SELECT TO bookshop_app USING (true);
CREATE POLICY comments_insert ON bookshop.comments FOR INSERT TO bookshop_app
  WITH CHECK (userid=(SELECT bookshop.current_user_id()) AND EXISTS (SELECT FROM bookshop.users u WHERE u.userid=comments.userid));
CREATE POLICY comments_admin ON bookshop.comments FOR ALL TO bookshop_app
  USING ((SELECT bookshop.is_admin())) WITH CHECK ((SELECT bookshop.is_admin()));
CREATE POLICY feedback_insert ON bookshop.feedback FOR INSERT TO bookshop_app WITH CHECK (true);
CREATE POLICY feedback_admin ON bookshop.feedback FOR ALL TO bookshop_app
  USING ((SELECT bookshop.is_admin())) WITH CHECK ((SELECT bookshop.is_admin()));
CREATE POLICY orders_read ON bookshop.orders FOR SELECT TO bookshop_app
  USING (customerid=(SELECT bookshop.current_user_id()) OR (SELECT bookshop.is_admin()));
CREATE POLICY orders_admin_update ON bookshop.orders FOR UPDATE TO bookshop_app
  USING ((SELECT bookshop.is_admin())) WITH CHECK ((SELECT bookshop.is_admin()));
CREATE POLICY orders_admin_delete ON bookshop.orders FOR DELETE TO bookshop_app USING ((SELECT bookshop.is_admin()));
CREATE POLICY orderdetails_read ON bookshop.orderdetails FOR SELECT TO bookshop_app
  USING ((SELECT bookshop.is_admin()) OR EXISTS (SELECT FROM bookshop.orders o
    WHERE o.orderid=orderdetails.orderid AND o.customerid=(SELECT bookshop.current_user_id())));

REVOKE ALL ON ALL TABLES IN SCHEMA bookshop FROM PUBLIC, bookshop_app;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA bookshop FROM PUBLIC, bookshop_app;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA bookshop FROM PUBLIC, bookshop_app;
GRANT USAGE ON SCHEMA bookshop TO bookshop_app;
GRANT SELECT,INSERT,UPDATE,DELETE ON bookshop.author,bookshop.categorys,bookshop.products,bookshop.product_details TO bookshop_app;
GRANT SELECT(userid,username,email,phone,address,role), UPDATE(username,password,email,phone,address) ON bookshop.users TO bookshop_app;
GRANT SELECT ON bookshop.orders,bookshop.orderdetails,bookshop.comments,bookshop.feedback TO bookshop_app;
GRANT UPDATE(status,senddate), DELETE ON bookshop.orders TO bookshop_app;
GRANT INSERT(productid,userid,content), UPDATE(content), DELETE ON bookshop.comments TO bookshop_app;
GRANT INSERT(name,email,phone,message), DELETE ON bookshop.feedback TO bookshop_app;
GRANT USAGE ON SEQUENCE bookshop.author_authorid_seq,bookshop.categorys_catid_seq,
  bookshop.products_productid_seq,bookshop.product_details_id_seq,
  bookshop.comments_id_seq,bookshop.feedback_feedbackid_seq TO bookshop_app;
GRANT EXECUTE ON FUNCTION bookshop.current_user_id(),bookshop.is_admin(),bookshop.login_record(text),
  bookshop.register_user(text,text,text,text,text),bookshop.admin_create_user(text,text,text,text,text,text),
  bookshop.admin_delete_user(bigint),bookshop.checkout(jsonb,text,text,text,text) TO bookshop_app;


"""Convert ONLY public catalog inserts from the legacy MySQL dump to PostgreSQL.

No SQL is executed and no user/contact/order/review records are copied. Run from
any directory; output is deterministic UTF-8. Unknown syntax fails closed.
"""
from pathlib import Path
import argparse
import re

ROOT = Path(__file__).resolve().parents[1]
TABLES = {
    "author": ("authorid", "authorname"),
    "categorys": ("catid", "catname"),
    "products": ("productid", "productname", "categoryid", "price", "qty", "photo", "authorid", "description"),
    "product_details": ("id", "product_id", "slug", "description", "pages", "authorid"),
}


def values(source):
    """Parse the narrow mysqldump VALUES grammar, not by splitting on commas."""
    i = 0
    rows = []
    escapes = {"0": "\0", "b": "\b", "n": "\n", "r": "\r", "t": "\t", "Z": "\x1a"}
    while i < len(source):
        if source[i].isspace() or source[i] == ',':
            i += 1
            continue
        if source[i] == ';':
            return rows
        if source[i] != '(':
            raise ValueError(f"Expected row at {i}")
        i += 1
        row = []
        while True:
            while source[i].isspace():
                i += 1
            if source[i] == "'":
                i += 1
                text = []
                while True:
                    ch = source[i]
                    i += 1
                    if ch == "\\":
                        ch = source[i]
                        i += 1
                        text.append(escapes.get(ch, ch))
                    elif ch == "'":
                        if source[i:i+1] == "'":
                            text.append("'")
                            i += 1
                        else:
                            break
                    else:
                        text.append(ch)
                row.append(''.join(text))
            else:
                match = re.match(r"NULL|-?\d+(?:\.\d+)?", source[i:])
                if not match:
                    raise ValueError(f"Unsupported literal at {i}")
                token = match.group()
                row.append(None if token == 'NULL' else int(token))
                i += len(token)
            while source[i].isspace():
                i += 1
            delim = source[i]
            i += 1
            if delim == ')':
                rows.append(row)
                break
            if delim != ',':
                raise ValueError(f"Expected delimiter at {i}")
    raise ValueError('Unterminated VALUES')


def literal(value):
    if value is None:
        return 'NULL'
    if isinstance(value, int):
        return str(value)
    if '\0' in value:
        raise ValueError('PostgreSQL text cannot contain NUL')
    return "'" + value.replace("'", "''") + "'"


def convert(source):
    catalog = {table: [] for table in TABLES}
    for match in re.finditer(r"INSERT INTO `([^`]+)`\s*\(([^)]+)\) VALUES\s*", source):
        table = match[1]
        if table not in TABLES:
            continue
        columns = tuple(c.strip().strip('`').lower() for c in match[2].split(','))
        if columns != TABLES[table]:
            raise ValueError(f'Unexpected columns in {table}: {columns}')
        catalog[table].extend(values(source[match.end():]))
    if any(not rows for rows in catalog.values()):
        raise ValueError('Missing catalog table')
    authors = {row[0] for row in catalog['author']}
    categories = {row[0] for row in catalog['categorys']}
    products = {row[0] for row in catalog['products']}
    for row in catalog['products']:
        if row[2] not in categories or row[6] not in authors or row[3] < 0 or row[4] < 0:
            raise ValueError(f'Invalid product catalog relationship/price/stock: {row[0]}')
    # Known legacy orphan: detail 96 references absent product 96. Do not invent
    # a sellable item (price/stock unknown); omit this detail with an audit note.
    orphan_details = [r[0] for r in catalog['product_details'] if r[1] not in products]
    if orphan_details != [96]:
        raise ValueError(f'Unexpected orphan details; review required: {orphan_details}')
    catalog['product_details'] = [r for r in catalog['product_details'] if r[1] in products]
    for row in catalog['product_details']:
        if row[1] not in products or row[5] not in authors or row[4] < 0:
            raise ValueError(f'Invalid product detail relationship/pages: {row[0]}')
    out = ['-- GENERATED by scripts/convert_catalog.py; CATALOG ONLY. Do not edit.',
           '-- Legacy personal users, orders, orderdetails, comments and feedback are deliberately omitted.',
           '-- Repair: omit orphan product_details id=96 (product 96 absent; no invented price/stock).',
           'BEGIN;', 'SET LOCAL standard_conforming_strings = on;']
    for table, columns in TABLES.items():
        out.append(f"INSERT INTO bookshop.{table} ({','.join(columns)}) VALUES")
        out.append(',\n'.join('(' + ','.join(map(literal, row)) + ')' for row in catalog[table]) + ';')
        pk = columns[0]
        out.append(f"SELECT pg_catalog.setval(pg_catalog.pg_get_serial_sequence('bookshop.{table}', '{pk}'), (SELECT max({pk}) FROM bookshop.{table}), true);")
    out.append('COMMIT;')
    return '\n'.join(out) + '\n', {k: len(v) for k, v in catalog.items()}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT / 'database/bookpalace.sql')
    parser.add_argument('--output', type=Path, default=ROOT / 'supabase/seed.sql')
    args = parser.parse_args()
    sql, counts = convert(args.source.read_text(encoding='utf-8-sig'))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(sql, encoding='utf-8', newline='\n')
    print(f'Catalog-only conversion: {counts}; output: {args.output}')
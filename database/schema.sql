    IF EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname=r) THEN
      EXECUTE pg_catalog.format('REVOKE ALL ON SCHEMA bookshop FROM %I',r);
      EXECUTE pg_catalog.format('REVOKE ALL ON ALL TABLES IN SCHEMA bookshop FROM %I',r);
      EXECUTE pg_catalog.format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA bookshop FROM %I',r);
      EXECUTE pg_catalog.format('REVOKE ALL ON ALL FUNCTIONS IN SCHEMA bookshop FROM %I',r);
    END IF;
  END LOOP;
END
$api$;
